-- 1. Create the call queue table
create table public.call_queue (
  id uuid default gen_random_uuid() primary key,
  number text not null,
  status text default 'idle',
  created_at timestamp with time zone default timezone('utc'::text, now()) not null,
  updated_at timestamp with time zone default timezone('utc'::text, now()) not null
);

-- 1.1. Enable Row Level Security (RLS)
alter table public.call_queue enable row level security;

-- 1.2. Create a temporary policy to allow your frontend to talk to it
-- (We will lock this down with a master password later)
create policy "Allow all access during development" 
on public.call_queue 
for all 
using (true);

-- 1.3. Enable Realtime WebSockets for this specific table
alter publication supabase_realtime add table public.call_queue;

