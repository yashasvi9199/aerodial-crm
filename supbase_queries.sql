-- 4. Create the justdial_leads table
create table public.justdial_leads (
    id bigint generated by default as identity primary key,
    created_at timestamp with time zone default timezone('utc'::text, now()) not null,
    name text not null,
    lead_name text,
    phone text not null unique,
    contacted text default 'No',
    follow_up text default 'No',
    notes text,
    profession text default 'Consumer',
    location text,
    updated_at timestamp with time zone default timezone('utc'::text, now()) not null
);

-- 4.1. Enable Realtime and RLS for justdial_leads
alter table public.justdial_leads replica identity full;
alter publication supabase_realtime add table public.justdial_leads;
alter table public.justdial_leads enable row level security;
create policy "Allow all access during development jd_leads" on public.justdial_leads for all using (true);

