-- 5. Create the call_logs table
create table public.call_logs (
    id bigint generated by default as identity primary key,
    created_at timestamp with time zone default timezone('utc'::text, now()) not null,
    phone_number text not null,
    duration_seconds integer default 0 not null,
    status text not null, -- 'Answered', 'Busy', 'Unanswered', 'Incorrect'
    call_date timestamp with time zone default timezone('utc'::text, now()) not null,
    call_type text default 'outgoing' not null,
    platform text not null, -- 'excel' or 'justdial'
    contact_id bigint references public.contacts(id) on delete set null,
    justdial_lead_id bigint references public.justdial_leads(id) on delete set null
);

-- 5.1. Enable Realtime and RLS for call_logs
alter table public.call_logs replica identity full;
alter publication supabase_realtime add table public.call_logs;
alter table public.call_logs enable row level security;
create policy "Allow all access during development call_logs" on public.call_logs for all using (true);

