-- 2. Create the system state table
create table public.system_state (
  id integer primary key default 1,
  adb_status text default 'disconnected',
  command text default 'idle',
  updated_at timestamp with time zone default timezone('utc'::text, now())
);

-- 2.1. Insert the single control row
insert into public.system_state (id, adb_status, command) values (1, 'disconnected', 'idle');

-- 2.2. Enable RLS and Realtime
alter table public.system_state enable row level security;
create policy "Allow all access during development state" on public.system_state for all using (true);
alter publication supabase_realtime add table public.system_state;

--------------------------------------------------------------------------------------

-- 3. Create the contacts table
create table public.contacts (
    id bigint generated by default as identity primary key,
    created_at timestamp with time zone default timezone('utc'::text, now()) not null,
    business_name text,
    phone_number text not null unique,
    poc_name text,
    profession text,
    location_city text,
    status_update text default 'Not Called',
    last_call_at text,
    call_duration text,
    follow_up text default 'No',
    call_back_date text,
    call_back_time text
);

-- 3.1. Enable Realtime for contacts table to sync status updates on the dashboard
alter table public.contacts replica identity full;
alter publication supabase_realtime add table public.contacts;