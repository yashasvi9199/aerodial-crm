-- 3. Create the contacts table
create table public.contacts (
    id bigint generated by default as identity primary key,
    created_at timestamp with time zone default timezone('utc'::text, now()) not null,
    business_name text,
    phone_number text not null unique,
    poc_name text,
    profession text,
    location_city text,
    status_update text default 'Not Called',
    last_call_at text,
    call_duration text,
    follow_up text default 'No',
    call_back_date text,
    call_back_time text
);

-- 3.1. Enable Realtime for contacts table to sync status updates on the dashboard
alter table public.contacts replica identity full;
alter publication supabase_realtime add table public.contacts;

-- 3.2. Enable Row Level Security and allow all operations during development
alter table public.contacts enable row level security;
create policy "Allow all access during development contacts" on public.contacts for all using (true);


